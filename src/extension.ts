import * as vscode from 'vscode';
import * as fs from 'fs';
import { parseLnkBuffer } from './lnkParser';
import { LnkEditorProvider } from './lnkEditorProvider';
import { parseAppImageBuffer } from './appImageParser';
import { AppImageEditorProvider } from './appImageEditorProvider';
import { PdfEditorProvider } from './pdfEditorProvider';

export function activate(context: vscode.ExtensionContext) {
  // 1. 注册 Windows .lnk 快捷方式自定义编辑器
  context.subscriptions.push(
    vscode.window.registerCustomEditorProvider(
      LnkEditorProvider.viewType,
      new LnkEditorProvider(context),
      {
        supportsMultipleEditorsPerDocument: false,
        webviewOptions: {
          retainContextWhenHidden: true
        }
      }
    )
  );

  // 2. 注册 Linux .AppImage 便携软件包自定义编辑器
  context.subscriptions.push(
    vscode.window.registerCustomEditorProvider(
      AppImageEditorProvider.viewType,
      new AppImageEditorProvider(context),
      {
        supportsMultipleEditorsPerDocument: false,
        webviewOptions: {
          retainContextWhenHidden: true
        }
      }
    )
  );

  // 3. 注册 PDF 文档离线预览自定义编辑器
  context.subscriptions.push(
    vscode.window.registerCustomEditorProvider(
      PdfEditorProvider.viewType,
      new PdfEditorProvider(context),
      {
        supportsMultipleEditorsPerDocument: true,
        webviewOptions: {
          retainContextWhenHidden: true
        }
      }
    )
  );

  // 4. 注册 .lnk 导出 TS 代码命令
  const lnkDumpCmd = vscode.commands.registerCommand('lnkViewer.dumpToCode', async (uri: vscode.Uri) => {
    let targetUri = uri || vscode.window.activeTextEditor?.document.uri;
    if (!targetUri || !targetUri.fsPath.toLowerCase().endsWith('.lnk')) {
      const selected = await vscode.window.showOpenDialog({
        canSelectFiles: true,
        canSelectFolders: false,
        canSelectMany: false,
        filters: {
          'Windows Shortcut (*.lnk)': ['lnk']
        },
        openLabel: 'Select .lnk File'
      });
      if (!selected || selected.length === 0) {
        return;
      }
      targetUri = selected[0];
    }

    try {
      const buffer = await fs.promises.readFile(targetUri.fsPath);
      const parsedData = parseLnkBuffer(buffer);

      const tsCode = `/**
 * Auto-generated by MS-SHLLINK Parser
 * File: ${targetUri.fsPath}
 */

export const lnkMetadata = ${JSON.stringify(parsedData, null, 2)} as const;
`;

      const doc = await vscode.workspace.openTextDocument({
        content: tsCode,
        language: 'typescript'
      });
      await vscode.window.showTextDocument(doc);
    } catch (err: any) {
      vscode.window.showErrorMessage(`解析失败: ${err.message}`);
    }
  });

  // 5. 注册 .AppImage 导出 TS 代码命令
  const appimageDumpCmd = vscode.commands.registerCommand('appimageViewer.dumpToCode', async (uri: vscode.Uri) => {
    let targetUri = uri || vscode.window.activeTextEditor?.document.uri;
    if (!targetUri || !targetUri.fsPath.toLowerCase().endsWith('.appimage')) {
      const selected = await vscode.window.showOpenDialog({
        canSelectFiles: true,
        canSelectFolders: false,
        canSelectMany: false,
        filters: {
          'Linux AppImage (*.AppImage)': ['AppImage', 'appimage']
        },
        openLabel: 'Select .AppImage File'
      });
      if (!selected || selected.length === 0) {
        return;
      }
      targetUri = selected[0];
    }

    try {
      const buffer = await fs.promises.readFile(targetUri.fsPath);
      const parsedData = parseAppImageBuffer(buffer);

      const tsCode = `/**
 * Auto-generated by AppImage Parser
 * File: ${targetUri.fsPath}
 */

export const appImageMetadata = ${JSON.stringify(parsedData, null, 2)} as const;
`;

      const doc = await vscode.workspace.openTextDocument({
        content: tsCode,
        language: 'typescript'
      });
      await vscode.window.showTextDocument(doc);
    } catch (err: any) {
      vscode.window.showErrorMessage(`解析失败: ${err.message}`);
    }
  });

  context.subscriptions.push(lnkDumpCmd, appimageDumpCmd);
}

export function deactivate() {}